export function getDailyPlayer(date: Date = new Date()): Player {
  const seed = date.getFullYear() * 10000 + (date.getMonth() + 1) * 100 + date.getDate();
  const index = seed % players.length;
  return players[index];
}

export function getDailyIndex(date: Date = new Date()): number {
  const start = new Date(2026, 0, 1).getTime();
  const diffDays = Math.floor((date.setHours(0, 0, 0, 0) - start) / 86400000);
  return diffDays + 1;
}
